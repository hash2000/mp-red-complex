#pragma once
#include <QString>
#include <optional>

/// Роль документа. Виджет при любой роли остаётся документом со всеми
/// обычными функциями, но роль даёт ему дополнительные привилегии и
/// ограничения по отношению к системе.
///
/// Правила роли применяет interceptor контекста (см. IContextInterceptor):
/// он решает, в каком контексте создаётся документ, какой у контекста
/// VariablesMode, разрешены ли события и изменение переменных.
enum class DocumentRule {
	/// Обычный документ — текущее поведение системы:
	/// контекст `.documents.{id}`, режим Lazy, переменные и события разрешены.
	Document,
	/// Документ системных настроек: контекст `.options`, режим Mutable.
	/// Даёт доступ к системным параметрам, которые лежат в глобальном контексте.
	SystemOptions,
};

/// Строковое имя роли (для описаний, диагностики и настроек).
QString documentRuleName(DocumentRule rule);

/// Роль по строковому имени; nullopt — имя не распознано.
std::optional<DocumentRule> documentRuleFromName(const QString& name);
