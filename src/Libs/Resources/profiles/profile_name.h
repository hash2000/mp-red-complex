#pragma once
#include <QString>

/// Соглашения об именах профилей пользователей.
///
/// Профиль — каталог в рабочей конфигурации: <path.profile>/profiles/<имя>.
/// Неавторизованный пользователь работает с профилем default, авторизованный —
/// с профилем, имя которого совпадает с его user hash.
namespace Profiles {

/// Имя профиля неавторизованного пользователя.
const QString& defaultName();

/// Имя профиля — это имя каталога, поэтому допускаются только строчная
/// латиница, цифры, подчёркивание и дефис.
bool isValidName(const QString& name);

} // namespace Profiles
